package com.example.leaderboard.leaderboard;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.anyIterable;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import com.example.leaderboard.player.Player;
import com.example.leaderboard.player.PlayerRepository;
import java.time.Instant;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.test.util.ReflectionTestUtils;

@ExtendWith(MockitoExtension.class)
class LeaderboardServiceTest {

    private static final UUID ALICE = UUID.fromString("00000000-0000-0000-0000-00000000000a");
    private static final UUID BOB = UUID.fromString("00000000-0000-0000-0000-00000000000b");

    @Mock
    private RedisLeaderboard leaderboard;
    @Mock
    private PlayerRepository playerRepository;

    private LeaderboardService service;

    @BeforeEach
    void setUp() {
        service = new LeaderboardService(leaderboard, playerRepository);
    }

    @Test
    void topReadsPositionsZeroToLimitMinusOne() {
        service.top(10);

        verify(leaderboard).findByPositionRange(0, 9);
    }

    @Test
    void topAddsUsernamesWithASingleRepositoryCall() {
        when(leaderboard.findByPositionRange(0, 1)).thenReturn(List.of(
                new RankedScore(ALICE, 900, 1),
                new RankedScore(BOB, 800, 2)));
        when(playerRepository.findAllById(List.of(ALICE, BOB)))
                .thenReturn(List.of(player(BOB, "bob"), player(ALICE, "alice"))); // order from the DB is arbitrary

        List<LeaderboardEntry> top = service.top(2);

        assertThat(top).containsExactly(
                new LeaderboardEntry(1, ALICE, "alice", 900),
                new LeaderboardEntry(2, BOB, "bob", 800));
        verify(playerRepository, times(1)).findAllById(anyIterable());
    }

    @ParameterizedTest(name = "rank {0}, range {1} -> positions {2}..{3}")
    @CsvSource({
            "1,  5, 0,  5",   // top of the board: nobody above
            "3,  5, 0,  7",   // fewer than `range` players above
            "50, 5, 44, 54",  // middle of the board
            "50, 25, 24, 74", // maximum range
    })
    void aroundRequestsAWindowCentredOnThePlayer(long rank, int range, long expectedStart, long expectedEnd) {
        when(leaderboard.findByPlayerId(ALICE)).thenReturn(Optional.of(new RankedScore(ALICE, 100, rank)));

        service.around(ALICE, range);

        verify(leaderboard).findByPositionRange(expectedStart, expectedEnd);
    }

    @Test
    void playerThrowsWhenNotOnTheBoard() {
        when(leaderboard.findByPlayerId(ALICE)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.player(ALICE)).isInstanceOf(PlayerNotRankedException.class);
    }

    @Test
    void aroundThrowsWhenNotOnTheBoard() {
        when(leaderboard.findByPlayerId(ALICE)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.around(ALICE, 5)).isInstanceOf(PlayerNotRankedException.class);
        verify(leaderboard, never()).findByPositionRange(anyLong(), anyLong());
    }

    private static Player player(UUID id, String username) {
        Player player = new Player(username, Instant.EPOCH);
        // The id is normally generated by Hibernate on insert; set it directly for this test.
        ReflectionTestUtils.setField(player, "id", id);
        return player;
    }
}
